import { describe, expect, it } from 'vitest'

import type { Category, Expense } from '@/lib/domain'
import type { RepeatCandidate } from '@/lib/repeatLast'
import { formatShortMoney } from '@/lib/money'
import {
  repeatLastCandidates,
  repeatLastLabel,
  repeatLastText,
} from '@/lib/repeatLast'

const NOW = new Date('2026-10-20T12:00:00.000Z')
const DAY = 86_400_000

function ago(days: number): string {
  return new Date(NOW.getTime() - days * DAY).toISOString()
}

let counter = 0
function expense(daysAgo: number, overrides: Partial<Expense> = {}): Expense {
  counter += 1
  return {
    id: `e${counter}`,
    amount: 65,
    currency: 'UAH',
    categoryId: 'cat-coffee',
    description: 'Coffee',
    createdAt: ago(daysAgo),
    ...overrides,
  }
}

const COFFEE: Category = { id: 'cat-coffee', name: 'Coffee', icon: '☕' }
const FOOD: Category = { id: 'cat-food', name: 'Food', icon: null }

describe('formatShortMoney', () => {
  it('shows whole numbers without decimals', () => {
    expect(formatShortMoney(65, 'UAH')).toBe('65 UAH')
    expect(formatShortMoney(100, 'EUR')).toBe('100 EUR')
  })

  it('shows other amounts with two decimals', () => {
    expect(formatShortMoney(12.5, 'USD')).toBe('12.50 USD')
    expect(formatShortMoney(0.5, 'EUR')).toBe('0.50 EUR')
    expect(formatShortMoney(3.14159, 'UAH')).toBe('3.14 UAH')
  })
})

describe('repeatLastCandidates: window and filters', () => {
  it('returns the shape the chips need', () => {
    const [candidate] = repeatLastCandidates([expense(1)], { now: NOW })

    expect(candidate).toEqual({
      key: 'coffee|cat-coffee|65|UAH',
      description: 'Coffee',
      categoryId: 'cat-coffee',
      amount: 65,
      currency: 'UAH',
      lastUsed: ago(1),
    })
  })

  it('skips entries generated by a recurring item', () => {
    const list = [
      expense(1, { recurringId: 'r1', description: 'Rent', amount: 5000 }),
      expense(2, { description: 'Tea', amount: 30 }),
    ]

    const result = repeatLastCandidates(list, { now: NOW })

    expect(result.map((c) => c.description)).toEqual(['Tea'])
  })

  it('keeps entries up to 60 days old and drops older ones', () => {
    const list = [
      expense(60, { description: 'Edge', amount: 1 }),
      expense(61, { description: 'Old', amount: 2 }),
    ]

    const result = repeatLastCandidates(list, { now: NOW })

    expect(result.map((c) => c.description)).toEqual(['Edge'])
  })

  it('honours the days option', () => {
    const list = [
      expense(5, { description: 'Recent', amount: 1 }),
      expense(20, { description: 'Middle', amount: 2 }),
    ]

    expect(
      repeatLastCandidates(list, { now: NOW, days: 10 }).map((c) => c.description),
    ).toEqual(['Recent'])
    expect(
      repeatLastCandidates(list, { now: NOW, days: 30 }).map((c) => c.description),
    ).toEqual(['Recent', 'Middle'])
  })

  it('drops entries dated after now', () => {
    const list = [expense(-2, { description: 'Future' }), expense(1)]

    const result = repeatLastCandidates(list, { now: NOW })

    expect(result.map((c) => c.description)).toEqual(['Coffee'])
  })

  it('returns nothing for no expenses', () => {
    expect(repeatLastCandidates([], { now: NOW })).toEqual([])
  })
})

describe('repeatLastCandidates: distinct keys', () => {
  it('merges the same description, category, amount and currency into one', () => {
    const list = [
      expense(5, { description: 'coffee ' }),
      expense(1, { description: '  Coffee' }),
      expense(3, { description: 'COFFEE' }),
    ]

    const result = repeatLastCandidates(list, { now: NOW })

    expect(result).toHaveLength(1)
    expect(result[0].lastUsed).toBe(ago(1))
    expect(result[0].description).toBe('Coffee')
  })

  it('keeps entries that differ in amount, currency or category apart', () => {
    const list = [
      expense(1, { amount: 65 }),
      expense(2, { amount: 70 }),
      expense(3, { currency: 'USD' }),
      expense(4, { categoryId: 'cat-food' }),
    ]

    const result = repeatLastCandidates(list, { now: NOW, limit: 10 })

    expect(result).toHaveLength(4)
    expect(new Set(result.map((c) => c.key)).size).toBe(4)
  })

  it('uses the most recent entry of a key for the candidate', () => {
    const older = expense(9, { description: 'Coffee' })
    const newer = expense(2, { description: 'Coffee' })

    const result = repeatLastCandidates([older, newer], { now: NOW })

    expect(result[0].lastUsed).toBe(newer.createdAt)
  })

  it('gives an empty description when there is none', () => {
    const list = [
      expense(1, { description: undefined, amount: 11 }),
      expense(2, { description: null, amount: 12 }),
      expense(3, { description: '   ', amount: 13 }),
    ]

    const result = repeatLastCandidates(list, { now: NOW })

    expect(result.map((c) => c.description)).toEqual(['', '', ''])
    expect(result.map((c) => c.amount)).toEqual([11, 12, 13])
  })
})

describe('repeatLastCandidates: order and limit', () => {
  const list = [
    expense(4, { description: 'D', amount: 4 }),
    expense(1, { description: 'A', amount: 1 }),
    expense(3, { description: 'C', amount: 3 }),
    expense(2, { description: 'B', amount: 2 }),
  ]

  it('sorts by the most recent use and returns 3 by default', () => {
    const result = repeatLastCandidates(list, { now: NOW })

    expect(result.map((c) => c.description)).toEqual(['A', 'B', 'C'])
  })

  it('honours the limit option', () => {
    expect(
      repeatLastCandidates(list, { now: NOW, limit: 1 }).map((c) => c.description),
    ).toEqual(['A'])
    expect(repeatLastCandidates(list, { now: NOW, limit: 4 })).toHaveLength(4)
  })

  it('does not mutate its input', () => {
    const copy = list.map((e) => e.id)

    repeatLastCandidates(list, { now: NOW })

    expect(list.map((e) => e.id)).toEqual(copy)
  })
})

describe('repeatLastText and repeatLastLabel', () => {
  const candidate: RepeatCandidate = {
    key: 'coffee|cat-coffee|65|UAH',
    description: 'Coffee',
    categoryId: 'cat-coffee',
    amount: 65,
    currency: 'UAH',
    lastUsed: ago(1),
  }

  it('builds the text from the description and the short amount', () => {
    expect(repeatLastText(candidate, COFFEE)).toBe('Coffee · 65 UAH')
    expect(
      repeatLastText({ ...candidate, description: 'Tea', amount: 12.5, currency: 'USD' }, COFFEE),
    ).toBe('Tea · 12.50 USD')
  })

  it('falls back to the category name when there is no description', () => {
    expect(
      repeatLastText({ ...candidate, description: '', categoryId: 'cat-food' }, FOOD),
    ).toBe('Food · 65 UAH')
  })

  it('prefixes the label with the category icon', () => {
    expect(repeatLastLabel(candidate, COFFEE)).toBe('☕ Coffee · 65 UAH')
    expect(
      repeatLastLabel(
        { ...candidate, description: '', amount: 7.5 },
        { id: 'cat-x', name: 'Taxi', icon: '🚕' },
      ),
    ).toBe('🚕 Taxi · 7.50 UAH')
  })

  it('has no prefix when the category has no icon or is unknown', () => {
    expect(repeatLastLabel(candidate, { ...COFFEE, icon: null })).toBe(
      'Coffee · 65 UAH',
    )
    expect(repeatLastLabel(candidate)).toBe('Coffee · 65 UAH')
  })
})
