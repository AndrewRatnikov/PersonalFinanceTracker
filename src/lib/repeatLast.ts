// "Repeat last" candidates for the dashboard chips. Pure: no IndexedDB, no
// React. It doesn't know about categories; the component drops candidates
// whose category is gone.

import { formatShortMoney } from './money'
import type { Category, Currency, Expense } from './domain'

export interface RepeatCandidate {
  key: string
  description: string
  categoryId: string
  amount: number
  currency: Currency
  lastUsed: string
}

const DAY_MS = 86_400_000

function groupKey(s: string): string {
  return s.trim().replace(/\s+/g, ' ').toLowerCase()
}

// The most recent distinct (description, category, amount, currency) entries
// of the last `days` days, newest first. Entries generated by a recurring item
// are skipped.
export function repeatLastCandidates(
  expenses: ReadonlyArray<Expense>,
  options: { now?: Date; days?: number; limit?: number } = {},
): Array<RepeatCandidate> {
  const { days = 60, limit = 3 } = options
  const now = (options.now ?? new Date()).getTime()
  const from = now - days * DAY_MS

  const byKey = new Map<string, { candidate: RepeatCandidate; time: number }>()
  for (const e of expenses) {
    if (e.recurringId !== undefined) continue
    const time = new Date(e.createdAt).getTime()
    if (Number.isNaN(time) || time < from || time > now) continue
    const description = (e.description ?? '').trim()
    const key = `${groupKey(description)}|${e.categoryId}|${e.amount}|${e.currency}`
    const existing = byKey.get(key)
    if (existing && existing.time >= time) continue
    byKey.set(key, {
      time,
      candidate: {
        key,
        description,
        categoryId: e.categoryId,
        amount: e.amount,
        currency: e.currency,
        lastUsed: e.createdAt,
      },
    })
  }

  return [...byKey.values()]
    .sort((a, b) => b.time - a.time)
    .slice(0, Math.max(0, limit))
    .map((v) => v.candidate)
}

// "Coffee · 65 UAH"; the category name stands in for a missing description.
export function repeatLastText(
  candidate: RepeatCandidate,
  category?: Category,
): string {
  const name = candidate.description || category?.name || ''
  const money = formatShortMoney(candidate.amount, candidate.currency)
  return name ? `${name} · ${money}` : money
}

// "☕ Coffee · 65 UAH"
export function repeatLastLabel(
  candidate: RepeatCandidate,
  category?: Category,
): string {
  const text = repeatLastText(candidate, category)
  return category?.icon ? `${category.icon} ${text}` : text
}
