// Builds docs/i18n/uk-review.md: one table row per Ukrainian message, with the
// English text next to it, for a native speaker's review. Type-only imports, so
// Node can run scripts/i18n-review.ts with type stripping.

export const REVIEW_FILE = 'docs/i18n/uk-review.md'

const PLURAL_CATEGORIES: ReadonlyArray<string> = ['zero', 'one', 'two', 'few', 'many', 'other']

function isPluralNode(node: unknown): node is Record<string, string> {
  if (typeof node !== 'object' || node === null) return false
  const keys = Object.keys(node)
  return keys.includes('other') && keys.every((k) => PLURAL_CATEGORIES.includes(k))
}

// Every leaf as [dotted key, text], in catalog order; plural forms become
// `key.one`, `key.few`, ...
export function flattenCatalog(catalog: object): Array<[string, string]> {
  const out: Array<[string, string]> = []
  const walk = (node: object, prefix: string) => {
    for (const [key, value] of Object.entries(node as Record<string, unknown>)) {
      const path = prefix === '' ? key : `${prefix}.${key}`
      if (typeof value === 'string') out.push([path, value])
      else if (isPluralNode(value)) {
        for (const [form, text] of Object.entries(value)) out.push([`${path}.${form}`, text])
      } else if (typeof value === 'object' && value !== null) walk(value, path)
    }
  }
  walk(catalog, '')
  return out
}

function cell(text: string): string {
  return text.replace(/\|/g, '\\|').replace(/\r?\n/g, '<br>')
}

// The English text of a flattened key; for a plural form English doesn't have
// (few, many), the English "other" form.
function englishFor(english: Map<string, string>, key: string): string {
  const own = english.get(key)
  if (own !== undefined) return own
  const dot = key.lastIndexOf('.')
  if (dot !== -1 && PLURAL_CATEGORIES.includes(key.slice(dot + 1))) {
    return english.get(`${key.slice(0, dot)}.other`) ?? ''
  }
  return ''
}

export function buildReviewMarkdown(en: object, uk: object): string {
  const english = new Map(flattenCatalog(en))
  const lines = [
    '# Ukrainian UI texts for review',
    '',
    'Generated by `npm run i18n:review` from `src/i18n/messages/en.ts` and `src/i18n/messages/uk.ts`. Do not edit by hand.',
    '',
    '| Key | English | Ukrainian |',
    '| --- | --- | --- |',
  ]
  for (const [key, text] of flattenCatalog(uk)) {
    lines.push(`| \`${key}\` | ${cell(englishFor(english, key))} | ${cell(text)} |`)
  }
  return `${lines.join('\n')}\n`
}
