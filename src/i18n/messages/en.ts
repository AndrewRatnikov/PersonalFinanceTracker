type PluralCategory = 'zero' | 'one' | 'two' | 'few' | 'many' | 'other'

type IsPluralNode<T> = T extends { other: string }
  ? Exclude<keyof T, PluralCategory> extends never
    ? true
    : false
  : false

// The shape every translation must have: the same tree as `en`, string leaves
// widened to string and each plural node with the Ukrainian categories.
type Localized<T> = {
  [K in keyof T]: T[K] extends string
    ? string
    : IsPluralNode<T[K]> extends true
      ? { one: string; few: string; many: string; other: string }
      : Localized<T[K]>
}

export type LocalizedMessages = Localized<typeof en>
